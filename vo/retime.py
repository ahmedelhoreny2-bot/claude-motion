"""Warp formol.timeline.json so each narration sentence starts with its scene; write captions + placement."""
import json, re, bisect
segs = json.load(open('vo/segments.json'))
orig = json.load(open('vo/timeline.orig.json'))
GAP = 0.35
anchors = [(0.0, 0.0)]
place = []
D, end = 0.0, -1.0
for s in segs:
    a = s['win'][0]
    n = max(a + D, end + GAP)
    D = n - a
    end = n + s['dur']
    anchors.append((a, n))
    place.append(n)
def warp(x):
    olds = [p[0] for p in anchors]
    i = bisect.bisect_right(olds, x) - 1
    if i >= len(anchors) - 1:
        return x + (anchors[-1][1] - anchors[-1][0])
    (a0, n0), (a1, n1) = anchors[i], anchors[i + 1]
    return n0 + (x - a0) * (n1 - n0) / (a1 - a0)
SKIP = {'fps', 'vol'}
def walk(o):
    if isinstance(o, dict):
        return {k: (v if k in SKIP else walk(v)) for k, v in o.items()}
    if isinstance(o, list):
        return [walk(v) for v in o]
    if isinstance(o, (int, float)):
        return round(warp(o), 2)
    return o
tl = walk(orig)
tl['fps'] = orig['fps']
tl['duration'] = round(max(warp(orig['duration']), place[-1] + segs[-1]['dur'] + 1.2), 1)
tl['outro']['end'] = tl['duration']
tl['outro']['fade'] = round(tl['duration'] - 0.8, 2)
json.dump(tl, open('formol.timeline.json', 'w'), indent=1, ensure_ascii=False)

caps = []
for i, s in enumerate(segs):
    if i == 0:
        continue
    st = place[i]
    en = st + s['dur'] + 0.4
    if i + 1 < len(segs):
        en = min(en, place[i + 1] - 0.12)
    txt = s['text'].replace('|', '').strip()
    caps.append(f"  [{st:.2f}, {en:.2f}, '{txt}'],")
open('src/formol/captions.ts', 'w').write(
    "/**\n * Narration (Modern Standard Arabic), shown as captions in sync with the voice-over.\n"
    " * Generated by vo/retime.py from examples/02-formol/narration-fusha.md and the aligned voice.\n"
    " * Text inside `backticks` renders as an LTR-isolated formula run.\n */\n"
    "export const CAPTIONS: [number, number, string][] = [\n" + "\n".join(caps) + "\n];\n")
json.dump([dict(n=s['n'], src=s['src'], at=round(place[i], 3)) for i, s in enumerate(segs)], open('vo/placement.json', 'w'), indent=1)
print('duration', tl['duration'], 'max shift', round(max(n - a for a, n in anchors), 2))
